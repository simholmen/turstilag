-- Fase 4: the stinettverk. A trail segment is one stretch of path between two junctions (or a dead
-- end); the network is the segments together, and a stikryss is where three or more of them meet.
-- Junctions aren't stored: the frontend works them out from shared endpoints, which the editor
-- snaps together while drawing.
--
-- Routes keep their own geometry for now. Building a route from segments comes later (4b).

CREATE TABLE public.trail_segments (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  hub_id bigint REFERENCES public.hubs(id) ON DELETE SET NULL,
  name text,
  geom geometry(LineString, 4326) NOT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);
CREATE INDEX trail_segments_hub_id_idx ON public.trail_segments (hub_id);
CREATE INDEX trail_segments_geom_idx ON public.trail_segments USING gist (geom);
CREATE TRIGGER set_updated_at_trail_segments BEFORE UPDATE ON public.trail_segments
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- RLS: same shape as routes — public read, admin write
ALTER TABLE public.trail_segments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Public read" ON public.trail_segments FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Admin insert" ON public.trail_segments FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY "Admin update" ON public.trail_segments FOR UPDATE TO authenticated USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY "Admin delete" ON public.trail_segments FOR DELETE TO authenticated USING ((SELECT public.is_admin()));

CREATE VIEW public.trail_segments_geojson WITH (security_invoker = true) AS
SELECT
  t.id::text AS id,
  t.hub_id::text AS hub_id,
  t.name,
  t.updated_at,
  ST_Length(t.geom::geography) AS length_m,
  ST_AsGeoJSON(t.geom)::json AS geometry
FROM public.trail_segments t;

-- Seed the network from the routes there are: noded so that routes crossing each other are split at
-- the crossing, and each piece takes the turområde of the route it came from. Only on an empty table,
-- so running this again adds nothing.
INSERT INTO public.trail_segments (hub_id, geom)
SELECT
  (SELECT r.hub_id FROM public.routes r ORDER BY ST_Distance(r.geom, ST_LineInterpolatePoint(piece.geom, 0.5)) LIMIT 1),
  piece.geom
FROM (
  SELECT (ST_Dump(ST_Node(ST_Collect(geom)))).geom AS geom FROM public.routes
) piece
WHERE NOT EXISTS (SELECT 1 FROM public.trail_segments)
  AND geometrytype(piece.geom) = 'LINESTRING'
  AND ST_Length(piece.geom::geography) > 1;
