    ST_SetSRID(ST_GeomFromGeoJSON(line_geojson::text), 4326), color, kind
  );
END
$$;

-- Sets the colour and/or type of the whole network; NULL leaves that one as it is per stretch
CREATE FUNCTION public.set_network_style_all(network_id bigint, new_color text DEFAULT NULL, new_kind text DEFAULT NULL)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  net geometry;
  src record;
BEGIN
  SELECT geom INTO net FROM public.trail_networks WHERE id = network_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Stinettverk % finnes ikke', network_id;
  END IF;
  UPDATE public.trail_network_segments s
  SET color = COALESCE(new_color, s.color), kind = COALESCE(new_kind, s.kind)
  WHERE s.network_id = set_network_style_all.network_id;
  -- Re-store so stretches that now look the same are joined
  SELECT * INTO src FROM public.network_sources(network_id);
  PERFORM public.network_store(network_id, net, src.geoms, src.colors, src.kinds);
END
$$;
