-- Stinettverk: every stretch has a colour (rød, blå, mørkeblå) and a line type — merket vei (solid),
-- turvei (dashed) or merket tursti (dotted) — so a tursti can turn into a turvei and back again.
--
-- trail_networks.geom stays the network's one dissolved line and keeps doing what it does: junctions,
-- snapping, overlap and tidying all work on it as before. The styles live beside it in
-- trail_network_segments, a set of lines that together cover the network exactly, each with one
-- colour and type. After every change network_store rebuilds them from the new geometry: it splits the
-- new lines wherever a stretch used to begin or end, gives each piece the style of the nearest old
-- stretch (or of the path just added), and joins pieces of the same style back together. Joining may
-- run a stretch through a junction; junctions are read from trail_networks.geom, never from these.
--
-- The networks there are now become rød merket tursti throughout.

CREATE TABLE public.trail_network_segments (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  network_id bigint NOT NULL REFERENCES public.trail_networks(id) ON DELETE CASCADE,
  color text NOT NULL DEFAULT 'rod' CHECK (color IN ('rod', 'bla', 'morkebla')),
  kind text NOT NULL DEFAULT 'tursti' CHECK (kind IN ('vei', 'turvei', 'tursti')),
  geom geometry(LineString, 4326) NOT NULL
);
CREATE INDEX trail_network_segments_network_id_idx ON public.trail_network_segments (network_id);
CREATE INDEX trail_network_segments_geom_idx ON public.trail_network_segments USING gist (geom);

ALTER TABLE public.trail_network_segments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Public read" ON public.trail_network_segments FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Admin insert" ON public.trail_network_segments FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY "Admin update" ON public.trail_network_segments FOR UPDATE TO authenticated USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY "Admin delete" ON public.trail_network_segments FOR DELETE TO authenticated USING ((SELECT public.is_admin()));

INSERT INTO public.trail_network_segments (network_id, geom)
SELECT n.id, d.geom FROM public.trail_networks n, ST_Dump(n.geom) d WHERE geometrytype(d.geom) = 'LINESTRING';

CREATE OR REPLACE VIEW public.trail_networks_geojson WITH (security_invoker = true) AS
SELECT
  n.id::text AS id,
  n.hub_id::text AS hub_id,
  n.name,
  n.description,
  n.updated_at,
  ST_AsGeoJSON(n.geom)::json AS geometry,
  COALESCE((
    SELECT json_agg(json_build_object('color', s.color, 'kind', s.kind, 'geometry', ST_AsGeoJSON(s.geom)::json) ORDER BY s.id)
    FROM public.trail_network_segments s WHERE s.network_id = n.id
  ), '[]'::json) AS segments
FROM public.trail_networks n;

-- The current stretches of a network, as parallel arrays
CREATE FUNCTION public.network_sources(nid bigint, OUT geoms geometry[], OUT colors text[], OUT kinds text[])
LANGUAGE sql
STABLE
AS $$
  SELECT COALESCE(array_agg(geom ORDER BY id), '{}'), COALESCE(array_agg(color ORDER BY id), '{}'), COALESCE(array_agg(kind ORDER BY id), '{}')
  FROM public.trail_network_segments WHERE network_id = nid
$$;

-- Saves a network's new geometry and rebuilds its stretches from `src_*` (the lines whose styles it
-- inherits). Whatever lies within 0.5 m of `prio_line` takes `prio_color`/`prio_kind` instead.
CREATE FUNCTION public.network_store(
  nid bigint, new_geom geometry, src_geoms geometry[], src_colors text[], src_kinds text[],
  prio_line geometry DEFAULT NULL, prio_color text DEFAULT NULL, prio_kind text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  pts geometry;
  piece geometry;
  mid geometry;
  best integer;
  c text;
  k text;
  out_geoms geometry[] := '{}';
  out_colors text[] := '{}';
  out_kinds text[] := '{}';
BEGIN
  -- Every place a stretch begins or ends is a place the new lines may need splitting
  SELECT ST_Collect(e.p) INTO pts FROM (
    SELECT ST_StartPoint(g) AS p FROM unnest(src_geoms) g
    UNION ALL SELECT ST_EndPoint(g) FROM unnest(src_geoms) g
    UNION ALL SELECT ST_StartPoint(prio_line) WHERE prio_line IS NOT NULL
    UNION ALL SELECT ST_EndPoint(prio_line) WHERE prio_line IS NOT NULL
  ) e;

  FOR piece IN
    SELECT (ST_Dump(CASE WHEN pts IS NULL THEN d.geom ELSE ST_Split(ST_Snap(d.geom, pts, 1e-7), pts) END)).geom
    FROM ST_Dump(new_geom) d
    WHERE geometrytype(d.geom) = 'LINESTRING'
  LOOP
    IF geometrytype(piece) <> 'LINESTRING' OR ST_Length(piece) = 0 THEN CONTINUE; END IF;
    mid := ST_LineInterpolatePoint(piece, 0.5);
    IF prio_line IS NOT NULL AND ST_DWithin(mid::geography, prio_line::geography, 0.5) THEN
      c := prio_color;
      k := prio_kind;
    ELSE
      SELECT i INTO best FROM generate_subscripts(src_geoms, 1) AS i ORDER BY ST_Distance(mid, src_geoms[i]) LIMIT 1;
      c := COALESCE(src_colors[best], 'rod');
      k := COALESCE(src_kinds[best], 'tursti');
    END IF;
    out_geoms := out_geoms || piece;
    out_colors := out_colors || c;
    out_kinds := out_kinds || k;
  END LOOP;

  UPDATE public.trail_networks SET geom = new_geom WHERE id = nid;
  DELETE FROM public.trail_network_segments s WHERE s.network_id = nid;
  INSERT INTO public.trail_network_segments (network_id, color, kind, geom)
  SELECT nid, m.c, m.k, m.g FROM (
    SELECT x.c, x.k, (ST_Dump(ST_LineMerge(ST_Collect(x.g)))).geom AS g
    FROM unnest(out_geoms, out_colors, out_kinds) AS x(g, c, k)
    GROUP BY x.c, x.k
  ) m
  WHERE geometrytype(m.g) = 'LINESTRING';
END
$$;

