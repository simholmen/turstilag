-- The added path's stretch gets `color`/`kind`
CREATE FUNCTION public.add_trail_to_network(
  network_id bigint, line_geojson json, snap_m double precision DEFAULT 8, color text DEFAULT 'rod', kind text DEFAULT 'tursti'
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  net geometry;
  line geometry := ST_SetSRID(ST_GeomFromGeoJSON(line_geojson::text), 4326);
  src record;
BEGIN
  SELECT geom INTO net FROM public.trail_networks WHERE id = network_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Stinettverk % finnes ikke', network_id;
  END IF;
  SELECT * INTO src FROM public.network_sources(network_id);
  PERFORM public.network_store(
    network_id, public.network_with_line(net, line, snap_m),
    src.geoms || line, src.colors || color, src.kinds || kind
  );
END
$$;

-- `segments` is the edited stretches, [{ color, kind, coordinates: [[lng, lat], …] }, …]. Stretches that
-- come back unchanged are kept as they are; the ones whose vertices were dragged are added again,
-- longest first, so one dragged onto another line merges into it. (`lines_geojson`, a plain
-- MultiLineString, is what the page sent before stretches had styles; it keeps the styles there are.)
CREATE FUNCTION public.set_network_geometry(
  network_id bigint, lines_geojson json DEFAULT NULL, snap_m double precision DEFAULT 8, segments json DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  src_geoms geometry[];
  src_colors text[];
  src_kinds text[];
  stored geometry[];
  net geometry;
  part geometry;
  src record;
BEGIN
  PERFORM 1 FROM public.trail_networks WHERE id = network_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Stinettverk % finnes ikke', network_id;
  END IF;
  SELECT * INTO src FROM public.network_sources(network_id);
  stored := src.geoms;

  IF segments IS NOT NULL THEN
    SELECT
      array_agg(ST_SetSRID(ST_GeomFromGeoJSON(json_build_object('type', 'LineString', 'coordinates', s -> 'coordinates')::text), 4326)),
      array_agg(s ->> 'color'),
      array_agg(s ->> 'kind')
    INTO src_geoms, src_colors, src_kinds
    FROM json_array_elements(segments) s;
  ELSE
    src_geoms := ARRAY(SELECT d.geom FROM ST_Dump(ST_SetSRID(ST_GeomFromGeoJSON(lines_geojson::text), 4326)) d);
    -- Styles come from the nearest stored stretch
    SELECT array_agg(src.colors[b.i]), array_agg(src.kinds[b.i]) INTO src_colors, src_kinds
    FROM unnest(src_geoms) WITH ORDINALITY g(geom, n)
    CROSS JOIN LATERAL (
      SELECT i FROM generate_subscripts(stored, 1) i ORDER BY ST_Distance(ST_LineInterpolatePoint(g.geom, 0.5), stored[i]) LIMIT 1
    ) b;
  END IF;

  SELECT public.network_merge(ST_Collect(g)) INTO net
  FROM unnest(src_geoms) g
  WHERE EXISTS (SELECT 1 FROM unnest(stored) s WHERE ST_NPoints(s) = ST_NPoints(g) AND ST_HausdorffDistance(s, g) < 1e-8);

  FOR part IN
    SELECT g FROM unnest(src_geoms) g
    WHERE ST_NPoints(g) >= 2
      AND NOT EXISTS (SELECT 1 FROM unnest(stored) s WHERE ST_NPoints(s) = ST_NPoints(g) AND ST_HausdorffDistance(s, g) < 1e-8)
    ORDER BY ST_Length(g::geography) DESC
  LOOP
    net := public.network_with_line(net, part, snap_m);
  END LOOP;

  PERFORM public.network_store(network_id, net, src_geoms, src_colors, src_kinds);
END
$$;

-- Removes one part of the network (1-based, in the order trail_networks.geom lists them)
CREATE FUNCTION public.remove_network_part(network_id bigint, part integer, snap_m double precision DEFAULT 8)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  net geometry;
  src record;
BEGIN
  SELECT geom INTO net FROM public.trail_networks WHERE id = network_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Stinettverk % finnes ikke', network_id;
  END IF;
  SELECT * INTO src FROM public.network_sources(network_id);
  PERFORM public.network_store(
    network_id,
    public.network_tidy((SELECT ST_Collect(d.geom) FROM ST_Dump(net) d WHERE d.path[1] <> part), snap_m),
    src.geoms, src.colors, src.kinds
  );
END
$$;

-- Gives the stretch of the network along `line_geojson` (drawn by the page along the network between
-- two clicked points) the colour and type
CREATE FUNCTION public.set_network_style(network_id bigint, line_geojson json, color text, kind text)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  net geometry;
  src record;
BEGIN
  SELECT geom INTO net FROM public.trail_networks WHERE id = network_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Stinettverk % finnes ikke', network_id;
  END IF;
  SELECT * INTO src FROM public.network_sources(network_id);
  PERFORM public.network_store(
