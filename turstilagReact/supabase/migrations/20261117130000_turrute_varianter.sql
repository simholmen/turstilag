-- ── Composing ─────────────────────────────────────────────────────────────────────────────────────
-- Where a stretch sits on the route, as fractions along it, and the line walked in its place.
-- An end within 2 m of the route is on it; the admin map snaps ends onto the line, so this is only
-- rounding. A stretch drawn from its far end, or against the route's direction, is turned around.
-- An omvei gives pos_from < pos_to; an avstikker gives pos_from = pos_to and the stretch out and back.
CREATE OR REPLACE FUNCTION public.route_alternative_placement(route geometry, alt geometry)
RETURNS TABLE (kind text, pos_from double precision, pos_to double precision, line geometry, off_m double precision)
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  start_m double precision := ST_Distance(ST_StartPoint(alt)::geography, route::geography);
  end_m double precision := ST_Distance(ST_EndPoint(alt)::geography, route::geography);
  a double precision;
  b double precision;
BEGIN
  IF end_m < start_m THEN
    alt := ST_Reverse(alt);
    SELECT end_m, start_m INTO start_m, end_m;
  END IF;
  a := ST_LineLocatePoint(route, ST_StartPoint(alt));
  off_m := start_m;

  IF end_m <= 2 THEN
    b := ST_LineLocatePoint(route, ST_EndPoint(alt));
    IF b < a THEN
      alt := ST_Reverse(alt);
      SELECT b, a INTO a, b;
    END IF;
    kind := 'omvei';
    pos_from := a;
    pos_to := b;
    line := alt;
  ELSE
    kind := 'avstikker';
    pos_from := a;
    pos_to := a;
    line := ST_MakeLine(alt, ST_Reverse(alt));
  END IF;
  RETURN NEXT;
END
$$;

-- The route with the stretches put in, walked from its start. A stretch that begins on a part another
-- one has already replaced can't be walked and is left out; `skipped` counts those, and the variant
-- trigger refuses such a set.
CREATE OR REPLACE FUNCTION public.route_variant_compose(route geometry, alts geometry[], OUT line geometry, OUT skipped int)
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  eps CONSTANT double precision := 1e-9;
  cur double precision := 0;
  parts geometry[] := '{}';
  p record;
BEGIN
  skipped := 0;
  FOR p IN
    SELECT pl.* FROM unnest(alts) a, public.route_alternative_placement(route, a) pl
    ORDER BY pl.pos_from, pl.pos_to
  LOOP
    IF p.pos_from < cur - eps THEN
      skipped := skipped + 1;
      CONTINUE;
    END IF;
    IF p.pos_from > cur + eps THEN
      parts := parts || ST_LineSubstring(route, cur, p.pos_from);
    END IF;
    parts := parts || p.line;
    cur := GREATEST(cur, p.pos_to);
  END LOOP;
  IF cur < 1 - eps THEN
    parts := parts || ST_LineSubstring(route, cur, 1);
  END IF;
  line := ST_RemoveRepeatedPoints(ST_MakeLine(parts));
END
$$;

-- A variant's stretches must belong to its route and fit together
CREATE OR REPLACE FUNCTION public.check_route_variant_alternatives()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v record;
  n int;
BEGIN
  SELECT rv.route_id, r.geom INTO v
  FROM public.route_variants rv JOIN public.routes r ON r.id = rv.route_id
  WHERE rv.id = NEW.variant_id;

  IF NOT EXISTS (SELECT 1 FROM public.route_alternatives WHERE id = NEW.alternative_id AND route_id = v.route_id) THEN
    RAISE EXCEPTION 'Strekningen hører til en annen rute';
  END IF;

  SELECT (public.route_variant_compose(v.geom, ARRAY(
    SELECT a.geom FROM public.route_variant_alternatives va
    JOIN public.route_alternatives a ON a.id = va.alternative_id
    WHERE va.variant_id = NEW.variant_id
  ))).skipped INTO n;
  IF n > 0 THEN
    RAISE EXCEPTION 'Strekningene i varianten overlapper hverandre';
  END IF;
  RETURN NULL;
END
$$;

CREATE CONSTRAINT TRIGGER check_route_variant_alternatives
AFTER INSERT OR UPDATE ON public.route_variant_alternatives
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.check_route_variant_alternatives();

-- ── Views ─────────────────────────────────────────────────────────────────────────────────────────
-- One line per route and variant: the route itself (variant_id NULL) and each variant composed
CREATE VIEW public.route_lines WITH (security_invoker = true) AS
SELECT r.id AS route_id, NULL::bigint AS variant_id, r.geom
FROM public.routes r
UNION ALL
SELECT v.route_id, v.id, (public.route_variant_compose(r.geom, ARRAY(
  SELECT a.geom FROM public.route_variant_alternatives va
  JOIN public.route_alternatives a ON a.id = va.alternative_id
  WHERE va.variant_id = v.id
))).line
FROM public.route_variants v
JOIN public.routes r ON r.id = v.route_id;

CREATE OR REPLACE VIEW public.routes_geojson WITH (security_invoker = true) AS
SELECT
  r.id::text AS id,
  r.hub_id::text AS hub_id,
  r.title,
  r.description,
  r.images,
  r.difficulty,
  r.shape,
  r.climb,
  r.direction,
  r.updated_at,
  ST_Length(r.geom::geography) / 1000 AS km,
  ST_AsGeoJSON(r.geom)::json AS geometry,
  r.variant_name
FROM public.routes r;

-- difficulty and climb are NULL where the variant goes by the route's
CREATE VIEW public.route_variants_geojson WITH (security_invoker = true) AS
SELECT
  v.id::text AS id,
  v.route_id::text AS route_id,
  v.name,
  v.difficulty,
  v.climb,
  v.description,
  v.sort_order,
  ST_Length(l.geom::geography) / 1000 AS km,
  ST_AsGeoJSON(l.geom)::json AS geometry,
  ARRAY(
    SELECT va.alternative_id::text FROM public.route_variant_alternatives va
    WHERE va.variant_id = v.id ORDER BY va.alternative_id
  ) AS alternative_ids
FROM public.route_variants v
JOIN public.route_lines l ON l.variant_id = v.id;

-- km is the stretch one way. detached: it no longer starts on the route — the route was redrawn
-- away from it — and should be drawn again.
CREATE VIEW public.route_alternatives_geojson WITH (security_invoker = true) AS
SELECT
  a.id::text AS id,
  a.route_id::text AS route_id,
  a.label,
  p.kind,
  ST_Length(a.geom::geography) / 1000 AS km,
  ST_AsGeoJSON(a.geom)::json AS geometry,
  p.off_m > 25 AS detached
FROM public.route_alternatives a
JOIN public.routes r ON r.id = a.route_id
CROSS JOIN LATERAL public.route_alternative_placement(r.geom, a.geom) p;

-- As before, per route line: variant_id is NULL for the route itself. A point on an avstikker gets
-- the km of the way out.
CREATE OR REPLACE VIEW public.route_features WITH (security_invoker = true) AS
WITH features AS (
  SELECT 'gjerdeklyvere'::text AS feature_table, g.id, 'gjerdeklyver'::text AS kind, g.subtypes, g.subtype_other, g.title, g.geom
  FROM public.gjerdeklyvere g
  UNION ALL
  SELECT 'other_points'::text, p.id, p.kind,
    CASE WHEN p.subtype IS NULL THEN '{}'::text[] ELSE ARRAY[p.subtype] END, NULL::text, p.title, p.geom
  FROM public.other_points p
),
located AS (
  SELECT
    r.route_id,
    r.variant_id,
    f.feature_table,
    f.id AS feature_id,
    f.kind,
    f.subtypes,
    f.subtype_other,
    f.title,
    geometrytype(f.geom) AS geom_type,
    ST_Length(r.geom::geography) / 1000 AS route_km,
    ST_LineLocatePoint(r.geom, public.feature_anchor(f.geom)) AS pos,
    CASE WHEN geometrytype(f.geom) = 'LINESTRING' THEN ST_LineLocatePoint(r.geom, ST_StartPoint(f.geom)) END AS pos_start,
    CASE WHEN geometrytype(f.geom) = 'LINESTRING' THEN ST_LineLocatePoint(r.geom, ST_EndPoint(f.geom)) END AS pos_end,
    ST_Length(f.geom::geography) AS length_m
  FROM public.route_lines r
  JOIN features f ON ST_DWithin(r.geom::geography, f.geom::geography, 15)
)
SELECT
  route_id::text AS route_id,
  feature_table,
  feature_id::text AS feature_id,
  kind,
  subtypes,
  subtype_other,
  title,
  geom_type,
  pos * route_km AS km,
  LEAST(pos_start, pos_end) * route_km AS km_fra,
  GREATEST(pos_start, pos_end) * route_km AS km_til,
  length_m,
  variant_id::text AS variant_id
FROM located;

CREATE OR REPLACE VIEW public.route_owners WITH (security_invoker = true) AS
SELECT DISTINCT
  r.route_id::text AS route_id,
  p.owner_id::text AS owner_id,
  r.variant_id::text AS variant_id
FROM public.route_lines r
JOIN public.parcels p ON ST_Intersects(r.geom, p.geom);

-- For the admin's variant editor: the length and line of a set of stretches before it is saved,
-- worked out by the same function the views use
CREATE OR REPLACE FUNCTION public.route_variant_preview(route_id bigint, alternative_ids bigint[])
RETURNS json
LANGUAGE sql
STABLE
AS $$
  SELECT json_build_object(
    'km', ST_Length(c.line::geography) / 1000,
    'geometry', ST_AsGeoJSON(c.line)::json,
    'skipped', c.skipped
  )
  FROM public.routes r
  CROSS JOIN LATERAL public.route_variant_compose(r.geom, ARRAY(
    SELECT a.geom FROM public.route_alternatives a
    WHERE a.route_id = r.id AND a.id = ANY (alternative_ids)
  )) c
  WHERE r.id = route_variant_preview.route_id
$$;
