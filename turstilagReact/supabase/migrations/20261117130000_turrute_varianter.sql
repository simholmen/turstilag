-- Turruter: named variants. The route as drawn is the variant "Standard" (named by variant_name, no
-- row of its own). The admin draws only the alternative stretches — the bits that differ — and a
-- variant is the route with some of them put in. A variant's line is composed here from the route and
-- its stretches, never stored, so redrawing the route carries every variant with it.
--
-- An alternative stretch starts on the route. If its other end also comes back onto the route it is
-- an omvei (detour): it replaces the route between its two ends — on a rundtur always the part that
-- doesn't hold the start, so every variant still begins and ends at the car park. If its other end
-- stays off the route it is an avstikker (side trip), walked out and back from where it leaves.

ALTER TABLE public.routes ADD COLUMN variant_name text;

CREATE TABLE public.route_alternatives (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  route_id bigint NOT NULL REFERENCES public.routes(id) ON DELETE CASCADE,
  label text,
  geom geometry(LineString, 4326) NOT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);
CREATE INDEX route_alternatives_route_id_idx ON public.route_alternatives (route_id);
CREATE TRIGGER set_updated_at_route_alternatives BEFORE UPDATE ON public.route_alternatives
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE public.route_variants (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  route_id bigint NOT NULL REFERENCES public.routes(id) ON DELETE CASCADE,
  name text NOT NULL,
  -- NULL: as the route
  difficulty text CHECK (difficulty IN ('gronn', 'bla', 'rod', 'svart')),
  climb text,
  description text,
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);
CREATE INDEX route_variants_route_id_idx ON public.route_variants (route_id);
CREATE TRIGGER set_updated_at_route_variants BEFORE UPDATE ON public.route_variants
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE public.route_variant_alternatives (
  variant_id bigint NOT NULL REFERENCES public.route_variants(id) ON DELETE CASCADE,
  alternative_id bigint NOT NULL REFERENCES public.route_alternatives(id) ON DELETE CASCADE,
  PRIMARY KEY (variant_id, alternative_id)
);
CREATE INDEX route_variant_alternatives_alternative_id_idx ON public.route_variant_alternatives (alternative_id);

