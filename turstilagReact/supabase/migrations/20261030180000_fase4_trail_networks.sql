-- Fase 4, revised: a stinettverk is one object — a name, a turområde and a single dissolved line
-- geometry with no start, end or length. Paths are added to it from an existing point on the network
-- (add_trail_to_network); where a new path runs along the network it is dropped, so overlapping
-- paths become one line, and its loose ends are tied onto the network so the two meet in a junction.
-- A piece between two junctions (or a junction and a dead end) can be removed again
-- (remove_network_part).
--
-- Replaces trail_segments from 20261030170000: its segments become one network per turområde, added
-- path by path so they get the same overlap handling.

CREATE TABLE public.trail_networks (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  hub_id bigint REFERENCES public.hubs(id) ON DELETE SET NULL,
  name text NOT NULL,
  description text,
  geom geometry(MultiLineString, 4326) NOT NULL DEFAULT 'SRID=4326;MULTILINESTRING EMPTY'::geometry,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);
CREATE INDEX trail_networks_hub_id_idx ON public.trail_networks (hub_id);
CREATE INDEX trail_networks_geom_idx ON public.trail_networks USING gist (geom);
CREATE TRIGGER set_updated_at_trail_networks BEFORE UPDATE ON public.trail_networks
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- RLS: same shape as routes — public read, admin write. The functions below run as the caller, so
-- they are bound by the same policies.
ALTER TABLE public.trail_networks ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Public read" ON public.trail_networks FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Admin insert" ON public.trail_networks FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY "Admin update" ON public.trail_networks FOR UPDATE TO authenticated USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY "Admin delete" ON public.trail_networks FOR DELETE TO authenticated USING ((SELECT public.is_admin()));

CREATE VIEW public.trail_networks_geojson WITH (security_invoker = true) AS
SELECT
  n.id::text AS id,
  n.hub_id::text AS hub_id,
  n.name,
  n.description,
  n.updated_at,
  ST_AsGeoJSON(n.geom)::json AS geometry
FROM public.trail_networks n;

-- Lines -> one MultiLineString: overlaps dissolved, crossings noded, and pieces that just continue
-- each other (a node only two of them share) joined, so every part runs junction to junction
CREATE FUNCTION public.network_merge(g geometry)
RETURNS geometry
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN g IS NULL OR ST_IsEmpty(ST_CollectionExtract(g, 2)) THEN 'SRID=4326;MULTILINESTRING EMPTY'::geometry
    ELSE ST_Multi(ST_LineMerge(ST_UnaryUnion(ST_CollectionExtract(g, 2))))
  END
$$;

-- Adds a drawn path (GeoJSON LineString) to a network. Whatever of it lies within 8 m of the network
-- is dropped, and each remaining piece that ends near the network is extended onto it.
CREATE FUNCTION public.add_trail_to_network(network_id bigint, line_geojson json)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  tol constant double precision := 8; -- metres
  net geometry;
  line geometry := ST_SetSRID(ST_GeomFromGeoJSON(line_geojson::text), 4326);
  pieces geometry[] := '{}';
  piece geometry;
BEGIN
  SELECT geom INTO net FROM public.trail_networks WHERE id = network_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Stinettverk % finnes ikke', network_id;
  END IF;

  IF ST_IsEmpty(net) THEN
    pieces := ARRAY[line];
  ELSE
    FOR piece IN
      SELECT (ST_Dump(ST_Difference(line, ST_Buffer(net::geography, tol)::geometry))).geom
    LOOP
      IF geometrytype(piece) <> 'LINESTRING' THEN CONTINUE; END IF;
      IF ST_DWithin(ST_StartPoint(piece)::geography, net::geography, tol + 1) THEN
        piece := ST_AddPoint(piece, ST_ClosestPoint(net, ST_StartPoint(piece)), 0);
      END IF;
      IF ST_DWithin(ST_EndPoint(piece)::geography, net::geography, tol + 1) THEN
        piece := ST_AddPoint(piece, ST_ClosestPoint(net, ST_EndPoint(piece)));
      END IF;
      pieces := pieces || piece;
    END LOOP;
    -- Give the network a vertex exactly where each piece meets it, so the union nodes them together
    IF array_length(pieces, 1) > 0 THEN
      net := ST_Snap(net, ST_Collect(pieces), 1e-7);
    END IF;
  END IF;

  UPDATE public.trail_networks SET geom = public.network_merge(ST_Collect(pieces || net)) WHERE id = network_id;
END
$$;

-- Removes one part (1-based, in the order the geometry lists them) and re-joins what is left
CREATE FUNCTION public.remove_network_part(network_id bigint, part integer)
RETURNS void
LANGUAGE sql
SECURITY INVOKER
AS $$
  UPDATE public.trail_networks n
  SET geom = public.network_merge((SELECT ST_Collect(d.geom) FROM ST_Dump(n.geom) d WHERE d.path[1] <> part))
  WHERE n.id = network_id;
$$;

-- ── trail_segments -> one network per turområde ────────────────────────────────────────────────────
DO $$
DECLARE
  grp record;
  seg record;
  new_id bigint;
BEGIN
  FOR grp IN
    SELECT s.hub_id, COALESCE(MIN(s.name), MIN(h.title), 'Stinettverk') AS name
    FROM public.trail_segments s
    LEFT JOIN public.hubs h ON h.id = s.hub_id
    GROUP BY s.hub_id
  LOOP
    INSERT INTO public.trail_networks (hub_id, name) VALUES (grp.hub_id, grp.name) RETURNING id INTO new_id;
    -- Longest first, so the main paths are kept and the short overlapping bits are trimmed
    FOR seg IN
      SELECT geom FROM public.trail_segments
      WHERE hub_id IS NOT DISTINCT FROM grp.hub_id
      ORDER BY ST_Length(geom::geography) DESC
    LOOP
      PERFORM public.add_trail_to_network(new_id, ST_AsGeoJSON(seg.geom)::json);
    END LOOP;
  END LOOP;
END
$$;

